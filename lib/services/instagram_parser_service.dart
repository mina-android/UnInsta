class InstagramParserService {
  /// Parses an Instagram export zip from in-memory bytes or file path.
  static Future<AnalysisResult> parseZipBytes(List<int> bytes) async {
    return compute(_parseZipInternal, bytes);
  }

  static AnalysisResult _parseZipInternal(List<int> bytes) {
    final archive = ZipDecoder().decodeBytes(bytes);

    final Map<String, InstagramUser> followers = {};
    final Map<String, InstagramUser> following = {};
    final List<InstagramUser> pendingRequests = [];
    final List<InstagramUser> recentlyUnfollowed = [];
    String? accountOwner;
    String? exportDate;

    for (final file in archive) {
      if (!file.isFile) continue;
      final fileName = file.name.replaceAll('\\', '/').toLowerCase();

      // Look for followers files
      final isFollowersFile = RegExp(r'(?:^|/)followers(?:_\d+)?\.(?:html|json)$').hasMatch(fileName) ||
          (fileName.contains('follower') && !fileName.contains('following') && (fileName.endsWith('.html') || fileName.endsWith('.json')));

      // Look for following files
      final isFollowingFile = RegExp(r'(?:^|/)following(?:\.html|_\d+\.html|\.json|_\d+\.json)$').hasMatch(fileName);

      // Look for pending requests files
      final isPendingFile = fileName.contains('pending_follow_requests') && (fileName.endsWith('.html') || fileName.endsWith('.json'));

      // Look for recently unfollowed profiles
      final isRecentlyUnfollowedFile = fileName.contains('recently_unfollowed') && (fileName.endsWith('.html') || fileName.endsWith('.json'));

      if (!isFollowersFile && !isFollowingFile && !isPendingFile && !isRecentlyUnfollowedFile) {
        continue;
      }

      final contentBytes = file.content as List<int>;
      final rawContent = utf8.decode(contentBytes, allowMalformed: true);

      // Extract metadata (owner & export timestamp) if present
      if (accountOwner == null) {
        final metaMatch = RegExp(
          r'Generated by\s+([a-zA-Z0-9._]+)\s+on\s+<time[^>]*datetime=[\x22\x27]([^\x22\x27]+)[\x22\x27]>([^<]+)</time>',
          caseSensitive: false,
        ).firstMatch(rawContent);
        if (metaMatch != null) {
          accountOwner = metaMatch.group(1);
          exportDate = metaMatch.group(3);
        }
      }

      if (isRecentlyUnfollowedFile) {
        if (fileName.endsWith('.json')) {
          recentlyUnfollowed.addAll(_parsePendingFromJson(rawContent));
        } else {
          recentlyUnfollowed.addAll(_parseTableFormatFromHtml(rawContent));
        }
      } else if (isPendingFile) {
        if (fileName.endsWith('.json')) {
          pendingRequests.addAll(_parsePendingFromJson(rawContent));
        } else {
          pendingRequests.addAll(_parseTableFormatFromHtml(rawContent));
        }
      } else if (isFollowersFile) {
        if (fileName.endsWith('.json')) {
          followers.addAll(_parseUsersFromJson(rawContent));
        } else {
          followers.addAll(_parseFollowersFromHtml(rawContent));
        }
      } else if (isFollowingFile) {
        if (fileName.endsWith('.json')) {
          following.addAll(_parseUsersFromJson(rawContent));
        } else {
          following.addAll(_parseFollowingFromHtml(rawContent));
        }
      }
    }

    final followersSet = followers.keys.toSet();
    final followingSet = following.keys.toSet();

    // Not following you back: accounts you follow who do not follow you
    final notFollowingBackKeys = followingSet.difference(followersSet).toList();
    // Fans: accounts following you that you do not follow back
    final fansKeys = followersSet.difference(followingSet).toList();
    // Mutual: accounts following each other
    final mutualKeys = followingSet.intersection(followersSet).toList();

    // Sort alphabetically by username by default
    notFollowingBackKeys.sort();
    fansKeys.sort();
    mutualKeys.sort();

    return AnalysisResult(
      followers: followers.values.toList(),
      following: following.values.toList(),
      notFollowingBack: notFollowingBackKeys.map((k) => following[k]!).toList(),
      fans: fansKeys.map((k) => followers[k]!).toList(),
      mutual: mutualKeys.map((k) => following[k]!).toList(),
      pendingRequests: pendingRequests,
      recentlyUnfollowedByMe: recentlyUnfollowed,
      accountOwner: accountOwner,
      exportDate: exportDate,
    );
  }

  // ---------------- HTML PARSING ----------------

  static Map<String, InstagramUser> _parseFollowersFromHtml(String html) {
    final Map<String, InstagramUser> result = {};
    final blocks = html.split(RegExp(r'<div class=[\x22\x27]pam _3-95'));

    if (blocks.length > 1) {
      for (var i = 1; i < blocks.length; i++) {
        final b = blocks[i];
        final userMatch = RegExp(r'href=[\x22\x27]https://www\.instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)[\x22\x27]').firstMatch(b);
        if (userMatch == null) continue;

        final uname = userMatch.group(1)!.trim();
        if (uname.isEmpty || uname.toLowerCase() == '_u') continue;

        final dateMatch = RegExp(r'<div>([A-Z][a-z]{2} \d{1,2}, \d{4} \d{1,2}:\d{2} [ap]m)</div>', caseSensitive: false).firstMatch(b);
        final dateStr = dateMatch?.group(1);

        final user = InstagramUser.create(
          username: uname,
          date: dateStr,
        );
        result[uname.toLowerCase()] = user;
      }
    } else {
      final matches = RegExp(r'href=[\x22\x27]https://www\.instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)[\x22\x27]').allMatches(html);
      for (final m in matches) {
        final uname = m.group(1)!.trim();
        if (uname.isNotEmpty && uname.toLowerCase() != '_u') {
          result.putIfAbsent(uname.toLowerCase(), () => InstagramUser.create(username: uname));
        }
      }
    }

    return result;
  }

  static Map<String, InstagramUser> _parseFollowingFromHtml(String html) {
    final Map<String, InstagramUser> result = {};
    final blocks = html.split(RegExp(r'<div class=[\x22\x27]pam _3-95'));

    if (blocks.length > 1) {
      for (var i = 1; i < blocks.length; i++) {
        final b = blocks[i];
        final userMatch = RegExp(r'href=[\x22\x27]https://www\.instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)[\x22\x27]').firstMatch(b);
        if (userMatch == null) continue;

        final uname = userMatch.group(1)!.trim();
        if (uname.isEmpty || uname.toLowerCase() == '_u') continue;

        final h2Match = RegExp(r'<h2[^>]*>(.*?)</h2>').firstMatch(b);
        final displayName = h2Match?.group(1);

        final dateMatch = RegExp(r'<div>([A-Z][a-z]{2} \d{1,2}, \d{4} \d{1,2}:\d{2} [ap]m)</div>', caseSensitive: false).firstMatch(b);
        final dateStr = dateMatch?.group(1);

        final user = InstagramUser.create(
          username: uname,
          displayName: displayName,
          date: dateStr,
        );
        result[uname.toLowerCase()] = user;
      }
    } else {
      final matches = RegExp(r'href=[\x22\x27]https://www\.instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)[\x22\x27]').allMatches(html);
      for (final m in matches) {
        final uname = m.group(1)!.trim();
        if (uname.isNotEmpty && uname.toLowerCase() != '_u') {
          result.putIfAbsent(uname.toLowerCase(), () => InstagramUser.create(username: uname));
        }
      }
    }

    return result;
  }

  static List<InstagramUser> _parseTableFormatFromHtml(String html) {
    final List<InstagramUser> list = [];
    final blocks = html.split(RegExp(r'<div class=[\x22\x27]pam _3-95 _2ph- _a6-g uiBoxWhite noborder[\x22\x27]'));

    for (var i = 1; i < blocks.length; i++) {
      final b = blocks[i];

      final userMatch = RegExp(r'>Username</td><td[^>]*>(.*?)</td>', caseSensitive: false).firstMatch(b);
      final nameMatch = RegExp(r'>Name</td><td[^>]*>(.*?)</td>', caseSensitive: false).firstMatch(b);
      final dateMatch = RegExp(r'<div class=[\x22\x27]_3-94 _a6-o[\x22\x27]>([^<]+)</div>').firstMatch(b);

      String? uname = userMatch?.group(1)?.trim();
      String? dname = nameMatch?.group(1)?.trim();
      String? date = dateMatch?.group(1)?.trim();

      if (uname == null || uname.isEmpty) {
        final linkMatch = RegExp(r'href=[\x22\x27]https://www\.instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)[\x22\x27]').firstMatch(b);
        if (linkMatch != null) {
          uname = linkMatch.group(1)!.trim();
        }
      }

      if (uname != null && uname.isNotEmpty && uname.toLowerCase() != '_u') {
        list.add(InstagramUser.create(
          username: uname,
          displayName: dname,
          date: date,
        ));
      }
    }

    if (list.isEmpty) {
      final userMatches = RegExp(r'>Username</td><td[^>]*>(.*?)</td>', caseSensitive: false).allMatches(html);
      for (final m in userMatches) {
        final uname = m.group(1)!.trim();
        if (uname.isNotEmpty) {
          list.add(InstagramUser.create(username: uname));
        }
      }
    }

    return list;
  }

  // ---------------- JSON PARSING ----------------

  static Map<String, InstagramUser> _parseUsersFromJson(String jsonStr) {
    final Map<String, InstagramUser> result = {};
    try {
      final dynamic parsed = jsonDecode(jsonStr);
      List<dynamic> items = [];

      if (parsed is List) {
        items = parsed;
      } else if (parsed is Map) {
        if (parsed['relationships_following'] is List) {
          items = parsed['relationships_following'];
        } else if (parsed['relationships_followers'] is List) {
          items = parsed['relationships_followers'];
        } else {
          for (final val in parsed.values) {
            if (val is List) {
              items = val;
              break;
            }
          }
        }
      }

      for (final item in items) {
        if (item is! Map) continue;
        String? username;
        String? displayName;
        String? dateStr;

        if (item['title'] is String && (item['title'] as String).isNotEmpty) {
          displayName = item['title'];
        }

        final stringList = item['string_list_data'];
        if (stringList is List && stringList.isNotEmpty) {
          final first = stringList[0];
          if (first is Map) {
            username = first['value']?.toString();
            final ts = first['timestamp'];
            if (ts is int && ts > 0) {
              final dt = DateTime.fromMillisecondsSinceEpoch(ts * 1000);
              dateStr = DateFormat('MMM dd, yyyy h:mm a').format(dt);
            }
            if ((username == null || username.isEmpty) && first['href'] is String) {
              final m = RegExp(r'instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)').firstMatch(first['href']);
              if (m != null) username = m.group(1);
            }
          }
        }

        username ??= displayName;
        if (username != null && username.isNotEmpty && username.toLowerCase() != '_u') {
          final user = InstagramUser.create(
            username: username,
            displayName: displayName != username ? displayName : null,
            date: dateStr,
          );
          result[username.toLowerCase()] = user;
        }
      }
    } catch (_) {}

    return result;
  }

  static List<InstagramUser> _parsePendingFromJson(String jsonStr) {
    final List<InstagramUser> result = [];
    try {
      final dynamic parsed = jsonDecode(jsonStr);
      List<dynamic> items = [];

      if (parsed is List) {
        items = parsed;
      } else if (parsed is Map) {
        if (parsed['relationships_follow_requests_sent'] is List) {
          items = parsed['relationships_follow_requests_sent'];
        } else if (parsed['relationships_unfollowed_users'] is List) {
          items = parsed['relationships_unfollowed_users'];
        } else {
          for (final val in parsed.values) {
            if (val is List) {
              items = val;
              break;
            }
          }
        }
      }

      for (final item in items) {
        if (item is! Map) continue;
        String? username;
        String? displayName;
        String? dateStr;

        if (item['title'] is String && (item['title'] as String).isNotEmpty) {
          displayName = item['title'];
        }

        final stringList = item['string_list_data'];
        if (stringList is List && stringList.isNotEmpty) {
          final first = stringList[0];
          if (first is Map) {
            username = first['value']?.toString();
            final ts = first['timestamp'];
            if (ts is int && ts > 0) {
              final dt = DateTime.fromMillisecondsSinceEpoch(ts * 1000);
              dateStr = DateFormat('MMM dd, yyyy h:mm a').format(dt);
            }
            if ((username == null || username.isEmpty) && first['href'] is String) {
              final m = RegExp(r'instagram\.com/(?:_u/)?([a-zA-Z0-9._]+)').firstMatch(first['href']);
              if (m != null) username = m.group(1);
            }
          }
        }

        username ??= displayName;
        if (username != null && username.isNotEmpty && username.toLowerCase() != '_u') {
          result.add(InstagramUser.create(
            username: username,
            displayName: displayName != username ? displayName : null,
            date: dateStr,
          ));
        }
      }
    } catch (_) {}

    return result;
  }
}
